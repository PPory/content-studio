// vault 里属于工作台的那一块，长什么样。**只写这一处。**
//
// 这几个名字原来散在六个文件里各写各的（`routes/vault.mjs` 两个、`routes/hot.mjs`、
// `routes/archive.mjs`、`lib/web-notes.mjs`、`lib/search.mjs` 一张表）。散着的时候
// 改一次布局要改六处，漏一处的表现是**那一类东西静默地读不到**——目录不存在时
// listBooks / listInsights 返回 null，界面显示的是「还没建」的空态引导，不是报错。
// 也就是说漏掉的那一处看起来像「你还没用过这个功能」。
//
// 为什么整块搬进 `99 - 个人工作台/`：vault 根目录下原来平铺着 书架/洞察/热点，
// 和「00 - 辛禾的知识库」这些手写的知识区混在一起，而它们的性质完全不同——
// 这几个目录是**工作台读写的**，人不该在里面手动整理文件。收进一个带序号的
// 一级目录之后，Obsidian 的文件树上一眼分得出「哪些是我写的、哪些是工具产的」。
//
// 序号的分配：01–04 是**你的字**（读的书、写的报告、发出去的稿、随手的批注），
// 09 是**机器抓的数据**（热点快照是 json，不是给人读的）。中间留着空号，
// 以后加一类东西不用重排已有的。
export const WB_ROOT = "99 - 个人工作台";

export const DIRS = {
  shelf: `${WB_ROOT}/01 - 书架`,
  insight: `${WB_ROOT}/02 - 洞察`,
  archive: `${WB_ROOT}/03 - 归档`,
  webnote: `${WB_ROOT}/04 - 网页批注`,
  plan: `${WB_ROOT}/05 - 计划`,
  knowledge: `${WB_ROOT}/06 - 知识卡片`,
  hot: `${WB_ROOT}/09 - 热点`,
  // 正文里插入的图片 / 视频 / GIF。按年月分子目录，一个目录几万个文件时 Obsidian 会很慢。
  media: `${WB_ROOT}/07 - 附件`,
};

// 「05 - 计划」是你手写的每日任务清单，一天一个 `YYYY-MM-DD.md`。它排在 01–04 那一组里，
// 因为它同样是**你的字**——工作台只是它的一个视图，主编辑器仍然可以是 Obsidian。
//
// ⚠️ **它故意不进 `search.mjs` 的 `VAULT_DIRS`。** 全局检索是拿来找「我当初存在哪儿了」的，
// 而任务清单一天一份、一份十几条短句，进了索引之后每搜一个常用词都会先撞上一堆
// 「买菜」「回消息」——**噪音会把真正要找的东西挤下去**。要加回来的话记得先想清楚这一条。

// 归档的成品落在这一层。**它不带序号**：序号是为了排序，而这是独子，没什么可排的。
// 同理书架里的 `<书名>/` 和洞察里的 `_material/` 也都不带——书名就是目录名
// （`listBooks` 直接拿它当书名），给书编号等于把编号写进书名里。
export const ARCHIVE_WORKS = `${DIRS.archive}/发布作品`;

/**
 * 一条 vault 相对路径落在书架里的哪本书上。`…/01 - 书架/纳瓦尔宝典/03 杠杆.md` → `纳瓦尔宝典`。
 *
 * 不在书架里、或者只到书架这一层，返回空串。
 */
export function bookOfPath(rel) {
  const prefix = `${DIRS.shelf}/`;
  if (!String(rel || "").startsWith(prefix)) return "";
  return rel.slice(prefix.length).split("/")[0] || "";
}
