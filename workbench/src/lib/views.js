/**
 * 总览的计数：counts 的键 → 点进去看哪个库的哪个状态。
 *
 * **分两组，因为 0 的含义正好相反。**
 * 「待初筛 / 待整理 / 撰写中」是 Worker 自己会消化的队列（5 分钟一轮初筛、14:00 聚类、
 * 成稿任务领走就跑），**0 是它们的正常态、也是好状态**；而「选题待写 / 待修改」不点它
 * 就永远不会动，0 才意味着手上没活了。
 *
 * 摊成一排同样大小的卡片时，这两类东西的视觉权重一样重，首屏最贵的一整行里大半在
 * 展示「没有事」，真正等你动手的数字反而混在几个 0 中间。所以第一组给大卡，
 * 第二组压成一条安静的细横条。
 */
